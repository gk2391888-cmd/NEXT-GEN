// NEXT GEN service worker: shows study reminders (web push) and opens the right page when one
// is tapped. It caches nothing, so students always get the latest notes and fixes.

self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', (event) => event.waitUntil(self.clients.claim()));

self.addEventListener('push', (event) => {
  let data = {};
  try {
    data = event.data ? event.data.json() : {};
  } catch {
    data = { body: event.data ? event.data.text() : '' };
  }
  const title = data.title || 'NEXT GEN';
  event.waitUntil(
    self.registration.showNotification(title, {
      body: data.body || 'Time for a quick practice.',
      icon: '/pwa-icon/192',
      badge: '/pwa-icon/96',
      tag: data.tag || 'nextgen',
      data: { url: data.url || '/' },
    }),
  );
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const url = new URL(event.notification.data?.url || '/', self.location.origin).href;
  event.waitUntil(
    self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then((windows) => {
      const open = windows.find((w) => w.url.startsWith(self.location.origin));
      if (open) {
        open.navigate(url);
        return open.focus();
      }
      return self.clients.openWindow(url);
    }),
  );
});
